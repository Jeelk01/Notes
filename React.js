// --------------------- Declarative Approach ---------------------
// ----------------------------------------------------------------
// declarative programming consists of instructing a program on what needs to be done, instead of telling it how to do it. 
{
        //     The declarative approach is a programming style where you specify _what_ you want to achieve, not _how_ to achieve it. It focuses on the desired outcome rather than the steps to get there, providing high-level abstraction and improved readability.

        // --> Key Features ---------------------------------------
        // - _End Results Focus_        : Specifies the desired outcome.
        // - _High-Level Abstraction_   : Hides implementation details.
        // - _Readability_              : More concise and understandable code.
        // - _Idempotency_              : Produces consistent results regardless of the initial state.

        // --> Examples -------------------------------------------
        // - _SQL_                      : Queries specify data to retrieve.
        // - _HTML/CSS_                 : Describes web page structure and style.
        // - _Configuration Management_ : Tools like Terraform define infrastructure state.
        // - _Functional Programming_   : Haskell functions specify what to compute.

        // --> Advantages -----------------------------------------
        // - _Simplicity_               : Easier to understand and maintain.
        // - _Modularity_               : Easier to reuse and compose components.
        // - _Parallelism_              : Easier to parallelize operations.

        // --> Disadvantages --------------------------------------
        // - _Performance_              : Potentially less efficient due to abstraction.
        // - _Flexibility_              : Less flexible for complex tasks.
        // - _Debugging_                : Harder to debug due to lack of explicit execution path.

        // In summary, the declarative approach simplifies programming by focusing on desired outcomes, making it intuitive and less error-prone for many use cases.
}