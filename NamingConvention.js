// ------------------------- Naming Convention -------------------------

// camelCase
// It is used for variables , functions/methods , properties , file name etc,
// capitalization of each word except the first is done.

// PascalCase
// It is used for component names , class name , thapes etc,
// Capitalization of each word is done.

// snake_case
// it is not common in javascript but used widely in python.
// each-word is separated by _ ( underscore ) and is in small letter.

// kebab-case
// it is common for fili naming , classnames , ids etc,
// each word is separated by - (Hyphen).