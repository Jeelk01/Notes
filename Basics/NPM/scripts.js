// NPM scripts

// NPM scripts are custom command that we define in Our Package.json file under script section. 

// These scripts allow us to automate tasks 
// building project 
// running tests
// starting servers
// formatting code


// Why it is used..?

// It replace long terminal command with short aliases
// Instead of typing long terminal commands every time, use scripts to:
// Save time
// Avoid mistakes
// Standardize workflows

// Automate the workflow --> build/test/lint/deploy
// Work cross platform

// How to run script
// npm run <script-name>


// how to define it

// package.json file --> scripts 

// then write custom scripts as key - value pair
// key as command name --> value as command for terminal





// Use Case            | Example Script
// --------------------------------------------------
// Start server        | "start": "node server.js"
// Run tests           | "test": "jest"
// Lint code           | "lint": "eslint ."
// Build project       | "build": "webpack"
// Watch file changes  | "dev": "webpack --watch"
// Format code         | "format": "prettier --write ."
// Deploy app          | "deploy": "vercel --prod"

