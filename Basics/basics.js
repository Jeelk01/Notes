// Node JS is not a programming language.
// Node JS is not a Technology,
// Node Js is not a Framework.
// Node JS is not a Library.

// It is a Javascript RunTime environment.

// In simple terms:
// It lets you run JavaScript outside the browser, on your computer/server.
// It gives JavaScript the ability to interact with things like the file system, network, and operating system, which browser JavaScript normally can’t do.

// We can not build backend using just javascript
// because it does't have functionalities that backend required

// What backend Requires
// A runtime environment to run server side code
// A web server to handle HTTP requests
// A database
// Authentication and security
// Hosting

// What pure javascript doesn't have to build backend

// Can't create server
// File system
// No access to operating system
// No direct database Connections
// No custom middleware or Routing
// No scheduled jobs or background tasks

