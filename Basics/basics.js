// Developed NodeJS

// Node JS = Javascript + V8 engine + LibUV ( for async I/O ) + npm

// Google's V8 engine
// Written in c++
// Runs your javascript code

// LibUV
// Handles the event loop, async I/O, thread pool
// written in C
// Makes node js non-blocking and scalable
// even javascript is single threaded allows nodejs to do many tasks at once
