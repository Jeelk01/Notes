# Escape Sequence
# Escape sequences in Python are special characters used in string literals, preceded by a backslash (\). 

# \'	Single quote	    'It\'s a string'            → It's a string
# \"	Double quote	    "He said, \"Hello!\""       → He said, "Hello!"
# \\	Backslash	        "C:\\path\\to\\file"        → C:\path\to\file
# \n	Newline	            "Hello\nWorld"              → Hello
#                                                         World
# \t	Horizontal tab	    "Hello\tWorld"              → Hello     World
# \r	Carriage return	    "Hello\rWorld"              → World
# \b	Backspace	        "Hello\bWorld"              → HellWorld
# \f	Form feed	        "Hello\fWorld"              → Hello (page break) World
# \v	Vertical tab	    "Hello\vWorld"              → Hello (vertical tab) World
# \a	ASCII Bell (Alert)	(Triggers a beep sound in some systems)
# \0	Null character	    "Hello\0World"              → HelloWorld
# \ooo	Octal value         (e.g., \101 for A)	"\101"  → A
# \xhh	Hexadecimal value   (e.g., \x41 for A)	"\x41"  → A

